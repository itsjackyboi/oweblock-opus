export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;
export const LINE_H = 9;

const CHARS = Object.keys(GLYPHS);
const INDEX = new Map(CHARS.map((c, i) => [c, i]));
const atlases = new Map();

function atlas(color) {
  let c = atlases.get(color);
  if (c) return c;
  c = document.createElement('canvas');
  c.width = CHARS.length * GLYPH_W;
  c.height = GLYPH_H;
  const g = c.getContext('2d');
  g.fillStyle = color;
  CHARS.forEach((ch, i) => {
    const rows = GLYPHS[ch].split('|');
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) {
        if (rows[y][x] === '#') g.fillRect(i * GLYPH_W + x, y, 1, 1);
      }
    }
  });
  atlases.set(color, c);
  return c;
}

export function measure(str, scale = 1) {
  return Math.max(0, str.length * ADVANCE - 1) * scale;
}

/**
 * Draw text. opts: { color, scale, align: 'left'|'center'|'right', shadow: color|null }
 * Returns the drawn width.
 */
export function drawText(ctx, str, x, y, opts = {}) {
  const scale = opts.scale || 1;
  const color = opts.color || '#ffffff';
  str = String(str).toUpperCase();
  const w = measure(str, scale);
  if (opts.align === 'center') x -= Math.floor(w / 2);
  else if (opts.align === 'right') x -= w;
  x = Math.round(x);
  y = Math.round(y);
  // Small text gets a diagonal drop shadow; big text gets a straight-down extrusion.
  if (opts.shadow) drawRaw(ctx, str, scale > 1 ? x : x + 1, y + scale, opts.shadow, scale);
  drawRaw(ctx, str, x, y, color, scale);
  return w;
}

function drawRaw(ctx, str, x, y, color, scale) {
  const a = atlas(color);
  for (let i = 0; i < str.length; i++) {
    const gi = INDEX.get(str[i]);
    if (gi === undefined) continue;
    ctx.drawImage(a, gi * GLYPH_W, 0, GLYPH_W, GLYPH_H, x + i * ADVANCE * scale, y, GLYPH_W * scale, GLYPH_H * scale);
  }
}
